-- B1 身份模型迁移：把「登录标识 → userId」的绑定关系和「Refresh Token 会话」从旧表结构里拆出来，
-- 为后续 userId-only 运行时链路提供事实表。本脚本只做建表与历史数据回填，不切换读取侧代码。

create sequence if not exists auth_identity_binding_id_seq start with 600001 increment by 1;

create table if not exists auth_identity_bindings (
    id bigint generated by default as identity primary key,
    created_time timestamptz not null,
    updated_time timestamptz not null,
    is_delete smallint not null default 0,
    identity_id bigint not null,
    user_id bigint not null,
    provider varchar(32) not null,
    identity_type varchar(32) not null,
    identity_hash varchar(255) not null,
    identity_cipher varchar(512),
    display_masked varchar(128),
    provider_subject varchar(255),
    union_subject varchar(255),
    verified smallint not null default 0,
    primary_identity smallint not null default 0,
    identity_status varchar(32) not null,
    bound_time timestamptz
);

