create sequence admin_role_id_seq start with 100000 increment by 1;
create sequence admin_permission_id_seq start with 200000 increment by 1;
create sequence admin_user_role_relation_id_seq start with 300000 increment by 1;
create sequence admin_role_permission_relation_id_seq start with 400000 increment by 1;
create sequence admin_access_session_id_seq start with 500000 increment by 1;
create sequence admin_operation_id_seq start with 600000 increment by 1;

comment on sequence admin_role_id_seq is '后台角色业务主键序列';
comment on sequence admin_permission_id_seq is '后台权限业务主键序列';
comment on sequence admin_user_role_relation_id_seq is '后台管理员角色关联业务主键序列';
comment on sequence admin_role_permission_relation_id_seq is '后台角色权限关联业务主键序列';
comment on sequence admin_access_session_id_seq is '后台会话业务主键序列';
comment on sequence admin_operation_id_seq is '后台操作业务主键序列';

create table admin_roles (
    id bigint generated by default as identity primary key,
    created_time timestamptz not null,
    updated_time timestamptz not null,
    is_delete smallint not null default 0,
    role_id bigint not null,
    role_code varchar(64) not null,
    role_name varchar(64) not null,
    role_description varchar(255),
    role_status varchar(32) not null
);

comment on table admin_roles is '后台角色表，保存后台角色定义，用于 RBAC 权限控制';
comment on column admin_roles.id is '数据库内部自增主键，只允许管理后台服务内部使用';
comment on column admin_roles.created_time is '创建时间';
comment on column admin_roles.updated_time is '更新时间';
comment on column admin_roles.is_delete is '是否逻辑删除，0-未删除，1-已删除';
comment on column admin_roles.role_id is '后台角色业务主键';
comment on column admin_roles.role_code is '后台角色编码，如 SUPER_ADMIN、CONTENT_REVIEWER、OPS_VIEWER';
comment on column admin_roles.role_name is '后台角色名称';
comment on column admin_roles.role_description is '角色职责说明';
comment on column admin_roles.role_status is '角色状态，如 ACTIVE、DISABLED';

create unique index uk_admin_roles_role_id_active on admin_roles (role_id) where is_delete = 0;
create unique index uk_admin_roles_role_code_active on admin_roles (role_code) where is_delete = 0;

